import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { saveAs } from 'file-saver';
import Papa from 'papaparse';
import type { ScoredRecommendation, SimulationResult, Hotspot } from '@/types';

export interface PDFReportData {
  title: string;
  cityName: string;
  createdAt: string;
  summary: string;
  stats: Record<string, number>;
  modelInfo: {
    modelName: string;
    rSquared: number;
    accuracy: number;
    valMAE: number;
  };
}

const BRAND = 'HeatX · Urban Climate Intelligence Platform';
const BRAND_ACCENT: [number, number, number] = [0, 229, 168];

function addFooter(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    const pageHeight = doc.internal.pageSize.getHeight();
    doc.setFontSize(7);
    doc.setTextColor(130, 140, 155);
    doc.text(BRAND, 14, pageHeight - 12);
    doc.text(`Page ${i} of ${pageCount}`, doc.internal.pageSize.getWidth() - 14, pageHeight - 12, { align: 'right' });
  }
}

export function exportPDF(data: PDFReportData) {
  const doc = new jsPDF();
  const pw = doc.internal.pageSize.getWidth();
  const ph = doc.internal.pageSize.getHeight();

  doc.setFillColor(3, 7, 18);
  doc.rect(0, 0, pw, ph, 'F');

  doc.setFillColor(BRAND_ACCENT[0], BRAND_ACCENT[1], BRAND_ACCENT[2]);
  doc.rect(0, 0, pw, 3, 'F');

  doc.setTextColor(249, 250, 251);
  doc.setFontSize(22);
  doc.text(data.title, 14, 30);

  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184);
  doc.text(`City: ${data.cityName}`, 14, 40);
  doc.text(`Generated: ${new Date(data.createdAt).toLocaleString()}`, 14, 46);

  doc.setDrawColor(40, 50, 70);
  doc.setLineWidth(0.3);
  doc.line(14, 52, pw - 14, 52);

  let y = 62;

  doc.setFontSize(13);
  doc.setTextColor(249, 250, 251);
  doc.text('Model Performance', 14, y);
  y += 8;

  autoTable(doc, {
    startY: y,
    head: [['Metric', 'Value']],
    body: [
      ['Model', data.modelInfo.modelName],
      ['R² Score', data.modelInfo.rSquared.toFixed(4)],
      ['Accuracy', `${data.modelInfo.accuracy.toFixed(1)}%`],
      ['Validation MAE', `${data.modelInfo.valMAE.toFixed(2)}°C`],
    ],
    theme: 'grid',
    headStyles: { fillColor: BRAND_ACCENT, textColor: [3, 7, 18], fontStyle: 'bold', fontSize: 9 },
    bodyStyles: { textColor: [249, 250, 251], fontSize: 8, fillColor: [12, 24, 44] },
    alternateRowStyles: { fillColor: [7, 17, 32] },
    styles: { cellPadding: 3, lineColor: [255, 255, 255], lineWidth: 0.05 },
    margin: { left: 14, right: 14 },
    tableLineColor: [255, 255, 255],
    tableLineWidth: 0.05,
  });
  y = (doc as any).lastAutoTable.finalY + 14;

  if (y > ph - 60) { doc.addPage(); y = 20; }

  doc.setFontSize(13);
  doc.setTextColor(249, 250, 251);
  doc.text('Summary', 14, y);
  y += 8;

  doc.setFontSize(9);
  doc.setTextColor(200, 210, 220);
  const summaryLines = doc.splitTextToSize(data.summary, pw - 28);
  doc.text(summaryLines, 14, y);
  y += summaryLines.length * 5 + 14;

  if (y > ph - 60) { doc.addPage(); y = 20; }

  doc.setFontSize(13);
  doc.setTextColor(249, 250, 251);
  doc.text('Key Statistics', 14, y);
  y += 8;

  const statEntries = Object.entries(data.stats);
  const statRows: string[][] = [];
  for (let i = 0; i < statEntries.length; i += 2) {
    const [k1, v1] = statEntries[i];
    const label1 = k1.replace(/([A-Z])/g, ' $1').trim();
    const val1 = typeof v1 === 'number' ? (v1 > 100 ? v1.toFixed(0) : v1.toFixed(2)) : String(v1);
    if (i + 1 < statEntries.length) {
      const [k2, v2] = statEntries[i + 1];
      const label2 = k2.replace(/([A-Z])/g, ' $1').trim();
      const val2 = typeof v2 === 'number' ? (v2 > 100 ? v2.toFixed(0) : v2.toFixed(2)) : String(v2);
      statRows.push([label1, val1, label2, val2]);
    } else {
      statRows.push([label1, val1, '', '']);
    }
  }

  if (statRows.length > 0) {
    autoTable(doc, {
      startY: y,
      head: [['Metric', 'Value', 'Metric', 'Value']],
      body: statRows,
      theme: 'grid',
      headStyles: { fillColor: BRAND_ACCENT, textColor: [3, 7, 18], fontStyle: 'bold', fontSize: 8 },
      bodyStyles: { textColor: [249, 250, 251], fontSize: 8, fillColor: [12, 24, 44] },
      alternateRowStyles: { fillColor: [7, 17, 32] },
      styles: { cellPadding: 3, lineColor: [255, 255, 255], lineWidth: 0.05 },
      margin: { left: 14, right: 14 },
      tableLineColor: [255, 255, 255],
      tableLineWidth: 0.05,
    });
    y = (doc as any).lastAutoTable.finalY + 14;
  }

  doc.setFontSize(7);
  doc.setTextColor(100, 120, 145);
  doc.text(`Generated by ${BRAND}`, 14, ph - 20);

  addFooter(doc);

  doc.save(`${data.title.replace(/\s+/g, '_').toLowerCase()}.pdf`);
}

export function exportCSV(filename: string, data: Record<string, unknown>[]) {
  const csv = Papa.unparse(data);
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8' });
  saveAs(blob, `${filename}.csv`);
}

export function exportGeoJSON(filename: string, features: Hotspot[]) {
  const geojson: GeoJSON.FeatureCollection = {
    type: 'FeatureCollection',
    features: features.map((h) => ({
      type: 'Feature',
      geometry: h.geometry,
      properties: {
        id: h.id,
        severity: h.severity,
        severity_score: h.severity_score,
        confidence: h.confidence,
        mean_temperature_c: h.mean_temperature_c,
        area_sq_km: h.area_sq_km,
        mean_ndvi: h.mean_ndvi,
        mean_ndbi: h.mean_ndbi,
        dominant_landcover: h.dominant_landcover,
        vegetation_fraction: h.vegetation_fraction,
        builtup_fraction: h.builtup_fraction,
      },
    })),
  };
  const blob = new Blob([JSON.stringify(geojson, null, 2)], { type: 'application/geo+json' });
  saveAs(blob, `${filename}.geojson`);
}

export function exportRecommendationCSV(recommendations: ScoredRecommendation[]) {
  exportCSV('recommendations', recommendations.map((r) => ({
    type: r.recommendation_type,
    label: r.label,
    priority: r.priority,
    cost: r.estimated_cost,
    temp_reduction: r.expected_temperature_reduction,
    carbon_reduction: r.carbon_reduction,
    cost_effectiveness: r.cost_effectiveness,
    feasibility: r.feasibility_score,
    overall_score: r.overall_score,
  })));
}

export function exportScenarioResults(results: SimulationResult[]) {
  exportCSV('scenario_comparison', results.map((r) => ({
    scenario: r.scenario_name,
    temp_reduction: r.mean_lst_change,
    max_reduction: r.max_lst_change,
    improvement_pct: r.pct_improvement,
    cost: r.estimated_cost,
    co2_reduction: r.estimated_co2_reduction,
    cost_effectiveness: r.cost_effectiveness,
  })));
}
